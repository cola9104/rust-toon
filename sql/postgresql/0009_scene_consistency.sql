-- Durable same-scene visual identity and state snapshots.
--
-- A scene master owns the stable spatial contract. Scene states describe only
-- durable changes inside that space (for example an intact door becoming
-- broken), while storyboards bind to the state they intend to render. Existing
-- generated storyboard images deliberately remain unclaimed because they were
-- produced before this contract existed.

CREATE UNIQUE INDEX IF NOT EXISTS uq_toonflow_images_id_assets_id
    ON toonflow.images(id, assets_id);

CREATE TABLE IF NOT EXISTS toonflow.scene_masters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    script_id bigint NOT NULL,
    scene_key text NOT NULL,
    name text NOT NULL DEFAULT '',
    scene_asset_id bigint,
    pinned_image_id bigint,
    spatial_prompt text NOT NULL DEFAULT '',
    layout_spec jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'missing_reference',
    source text NOT NULL DEFAULT 'manual',
    revision integer NOT NULL DEFAULT 1,
    create_time bigint NOT NULL DEFAULT
        ((extract(epoch FROM clock_timestamp()) * 1000)::bigint),
    update_time bigint NOT NULL DEFAULT
        ((extract(epoch FROM clock_timestamp()) * 1000)::bigint),
    CONSTRAINT scene_masters_scope_unique
        UNIQUE (project_id, script_id, scene_key),
    CONSTRAINT scene_masters_script_project_fk
        FOREIGN KEY (script_id, project_id)
        REFERENCES toonflow.scripts(id, project_id)
        ON DELETE CASCADE,
    CONSTRAINT scene_masters_scene_asset_fk
        FOREIGN KEY (scene_asset_id)
        REFERENCES toonflow.assets(id)
        ON DELETE NO ACTION
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT scene_masters_pinned_image_asset_fk
        FOREIGN KEY (pinned_image_id, scene_asset_id)
        REFERENCES toonflow.images(id, assets_id)
        ON DELETE SET NULL (pinned_image_id),
    CONSTRAINT scene_masters_reference_pair_complete
        CHECK (pinned_image_id IS NULL OR scene_asset_id IS NOT NULL),
    CONSTRAINT scene_masters_scene_key_canonical
        CHECK (scene_key ~ '^sc[1-9][0-9]*$'),
    CONSTRAINT scene_masters_layout_spec_is_object
        CHECK (jsonb_typeof(layout_spec) = 'object'),
    CONSTRAINT scene_masters_status_valid
        CHECK (status IN ('ready', 'missing_reference', 'needs_review')),
    CONSTRAINT scene_masters_source_valid
        CHECK (source IN ('manual', 'director', 'agent', 'backfill')),
    CONSTRAINT scene_masters_revision_positive CHECK (revision > 0)
);

CREATE TABLE IF NOT EXISTS toonflow.scene_states (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scene_master_id bigint NOT NULL,
    state_key text NOT NULL,
    name text NOT NULL DEFAULT '',
    parent_state_id bigint,
    sequence integer NOT NULL,
    change_summary text NOT NULL DEFAULT '',
    state_prompt text NOT NULL DEFAULT '',
    object_states jsonb NOT NULL DEFAULT '{}'::jsonb,
    source text NOT NULL DEFAULT 'manual',
    revision integer NOT NULL DEFAULT 1,
    create_time bigint NOT NULL DEFAULT
        ((extract(epoch FROM clock_timestamp()) * 1000)::bigint),
    update_time bigint NOT NULL DEFAULT
        ((extract(epoch FROM clock_timestamp()) * 1000)::bigint),
    CONSTRAINT scene_states_master_sequence_unique
        UNIQUE (scene_master_id, sequence),
    CONSTRAINT scene_states_master_key_unique
        UNIQUE (scene_master_id, state_key),
    CONSTRAINT scene_states_id_master_unique
        UNIQUE (id, scene_master_id),
    CONSTRAINT scene_states_master_fk
        FOREIGN KEY (scene_master_id)
        REFERENCES toonflow.scene_masters(id)
        ON DELETE CASCADE,
    CONSTRAINT scene_states_parent_same_master_fk
        FOREIGN KEY (parent_state_id, scene_master_id)
        REFERENCES toonflow.scene_states(id, scene_master_id)
        ON DELETE CASCADE,
    CONSTRAINT scene_states_state_key_canonical
        CHECK (state_key ~ '^[a-z][a-z0-9_-]{0,63}$'),
    CONSTRAINT scene_states_sequence_non_negative CHECK (sequence >= 0),
    CONSTRAINT scene_states_base_parent_contract
        CHECK (
            (state_key = 'base' AND sequence = 0 AND parent_state_id IS NULL)
            OR (state_key <> 'base' AND sequence > 0 AND parent_state_id IS NOT NULL)
        ),
    CONSTRAINT scene_states_parent_not_self
        CHECK (parent_state_id IS NULL OR parent_state_id <> id),
    CONSTRAINT scene_states_object_states_is_object
        CHECK (jsonb_typeof(object_states) = 'object'),
    CONSTRAINT scene_states_source_valid
        CHECK (source IN ('manual', 'director', 'agent', 'backfill', 'system')),
    CONSTRAINT scene_states_revision_positive CHECK (revision > 0)
);

