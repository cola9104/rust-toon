-- Create one logical master per persisted canonical scene. A master is ready
-- only when every storyboard has exactly one scene-asset binding, every binding
-- belongs to the storyboard project, all boards select the same asset, and that
-- asset's selected image is complete and addressable. Missing, cross-project,
-- multi-bound, and divergent boards remain unclaimed rather than being guessed.
WITH storyboard_scene_assets AS (
    SELECT storyboard.id AS storyboard_id,
           storyboard.project_id,
           storyboard.script_id,
           storyboard.scene_key,
           count(asset.id) FILTER (WHERE asset.type = 'scene') AS scene_binding_count,
           count(asset.id) FILTER (
               WHERE asset.type = 'scene'
                 AND asset.project_id = storyboard.project_id
           ) AS same_project_scene_binding_count,
           min(asset.id) FILTER (
               WHERE asset.type = 'scene'
                 AND asset.project_id = storyboard.project_id
           ) AS only_same_project_scene_asset_id
    FROM toonflow.storyboards storyboard
    LEFT JOIN toonflow.assets_storyboards binding
      ON binding.storyboard_id = storyboard.id
    LEFT JOIN toonflow.assets asset ON asset.id = binding.asset_id
    WHERE storyboard.scene_key ~ '^sc[1-9][0-9]*$'
    GROUP BY storyboard.id, storyboard.project_id,
             storyboard.script_id, storyboard.scene_key
),
scene_asset_summary AS (
    SELECT board.project_id,
           board.script_id,
           board.scene_key,
           count(*) AS storyboard_count,
           count(*) FILTER (
               WHERE board.scene_binding_count = 1
                 AND board.same_project_scene_binding_count = 1
           ) AS valid_storyboard_count,
           count(DISTINCT board.only_same_project_scene_asset_id) FILTER (
               WHERE board.scene_binding_count = 1
                 AND board.same_project_scene_binding_count = 1
           ) AS selected_asset_count,
           min(board.only_same_project_scene_asset_id) FILTER (
               WHERE board.scene_binding_count = 1
                 AND board.same_project_scene_binding_count = 1
           ) AS only_scene_asset_id,
           sum(board.scene_binding_count) AS total_scene_binding_count
    FROM storyboard_scene_assets board
    GROUP BY board.project_id, board.script_id, board.scene_key
),
selected_masters AS (
    SELECT summary.*,
           summary.valid_storyboard_count = summary.storyboard_count
             AND summary.selected_asset_count = 1 AS has_unanimous_scene_asset
    FROM scene_asset_summary summary
),
resolved_masters AS (
    SELECT selected.*,
           CASE WHEN selected.has_unanimous_scene_asset
                THEN asset.id
                ELSE NULL
           END AS scene_asset_id,
           CASE WHEN selected.has_unanimous_scene_asset
                     AND image.id IS NOT NULL
                THEN image.id
                ELSE NULL
           END AS pinned_image_id,
           asset.name AS asset_name,
           asset.prompt AS asset_prompt,
           asset.description AS asset_description
    FROM selected_masters selected
    LEFT JOIN toonflow.assets asset
      ON asset.id = selected.only_scene_asset_id
     AND asset.project_id = selected.project_id
     AND asset.type = 'scene'
     AND selected.has_unanimous_scene_asset
    LEFT JOIN toonflow.images image
      ON image.id = asset.image_id
     AND image.assets_id = asset.id
     AND image.state = '已完成'
     AND coalesce(image.file_path, '') <> ''
)
INSERT INTO toonflow.scene_masters(
    project_id, script_id, scene_key, name, scene_asset_id, pinned_image_id,
    spatial_prompt, layout_spec, status, source
)
SELECT selected.project_id,
       selected.script_id,
       selected.scene_key,
       coalesce(nullif(selected.asset_name, ''), selected.scene_key),
       selected.scene_asset_id,
       selected.pinned_image_id,
       coalesce(nullif(selected.asset_prompt, ''),
                nullif(selected.asset_description, ''), ''),
       '{}'::jsonb,
       CASE
           WHEN selected.pinned_image_id IS NOT NULL THEN 'ready'
           WHEN selected.has_unanimous_scene_asset THEN 'missing_reference'
           WHEN selected.total_scene_binding_count > 0 THEN 'needs_review'
           ELSE 'missing_reference'
       END,
       'backfill'
FROM resolved_masters selected
ON CONFLICT (project_id, script_id, scene_key) DO NOTHING;

INSERT INTO toonflow.scene_states(
    scene_master_id, state_key, name, parent_state_id, sequence,
    change_summary, state_prompt, object_states, source
)
SELECT master.id,
       'base',
       '初始状态',
       NULL,
       0,
       '',
       '',
       '{}'::jsonb,
       'backfill'
FROM toonflow.scene_masters master
WHERE NOT EXISTS (
    SELECT 1 FROM toonflow.scene_states state
    WHERE state.scene_master_id = master.id AND state.state_key = 'base'
)
ON CONFLICT (scene_master_id, state_key) DO NOTHING;

UPDATE toonflow.storyboards storyboard
SET scene_state_id = state.id
FROM toonflow.scene_masters master
JOIN toonflow.scene_states state
  ON state.scene_master_id = master.id
 AND state.state_key = 'base'
WHERE storyboard.project_id = master.project_id
  AND storyboard.script_id = master.script_id
  AND storyboard.scene_key = master.scene_key
  AND storyboard.scene_state_id IS NULL;

