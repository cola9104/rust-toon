run_sub_agent_script(prompt: "<按模板构建的具体指令>")
```

### 派发审核任务

**前置条件：仅当执行层正常完成任务并返回成功确认消息时，才触发审核流程。若执行层未正常完成，直接告知用户任务未完成并结束，不得触发审核。**

每个阶段执行完毕后，决策层按以下流程操作：

1. 收到执行层返回的确认消息（如"故事骨架已保存，请在右侧工作台查看。"）
