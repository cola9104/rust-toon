```

### 审核结果处理

监督层返回审核报告后，决策层**必须将报告展示给用户，并等待用户回复后才能进行下一步操作**。

展示报告时，根据评分附带不同的引导语：

| 评分 | 引导语 |
|------|--------|
| A | 展示报告 + "审核通过，是否进入下一阶段？" |
| B | 展示报告 + "有一些小问题，是否需要修复还是直接继续？" |
| C | 展示报告 + "建议修复以下问题，您希望修复哪些？" |
| D | 展示报告 + "建议重做此阶段，您确认吗？" |

**⚠️ 展示报告后必须停下来等待用户回复，收到用户明确指示前不得派发任何新任务给执行层。**

